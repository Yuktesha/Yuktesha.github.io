GEMMA_PRAISE_PROMPT = """你是一位幽默機智、文采斐然的文壇星盤神算大師。
請針對以下職業及其核心行話，為成語接龍遊戲《字戀》結算頁面創作充滿趣味、文采飛揚且具有本土溫度的「職業神算推測」：

【職業名稱】：{name}
【核心關鍵詞】：{keywords}

請嚴格輸出 JSON 物件：
{{
  "tag": "✨ 專屬星盤標籤（含 Emoji）",
  "title": "幽默且具創意的神算推測稱謂（如「堪比化鵬巨鯤海空職業軍人就是您？」）",
  "desc": "結合該職業特色與成語對弈技巧的俏皮讚美（50~80 字）"
}}
"""

def query_gemma_api(prompt_text):
    gemini_api_key = os.environ.get("GEMINI_API_KEY")
    if not gemini_api_key:
        return None
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key={gemini_api_key}"
    payload = {
        "contents": [{"parts": [{"text": prompt_text}]}],
        "generationConfig": {
            "temperature": 0.7,
            "responseMimeType": "application/json"
        }
    }
    try:
        req = urllib.request.Request(
            url,
            data=json.dumps(payload).encode('utf-8'),
            headers={"Content-Type": "application/json"}
        )
        with urllib.request.urlopen(req, timeout=20) as resp:
            data = json.loads(resp.read().decode('utf-8'))
            text = data['candidates'][0]['content']['parts'][0]['text']
            return json.loads(text)
    except Exception as e:
        print(f"Gemma API 呼叫略過 (使用預設高品質神算庫): {e}")
        return None

def build_career_database():
    output_path = os.path.join(BASE_DIR, 'career_database.js')
    careers = []

    print("🔮 開始構建百工百業行話數據庫...")
    for item in PROFESSIONS_TAXONOMY:
        print(f"  -> 處理領域：{item['name']}...")
        gemma_res = query_gemma_api(GEMMA_PRAISE_PROMPT.format(
            name=item['name'],
            keywords="、".join(item['keywords'][:10])
        ))

        if gemma_res and "title" in gemma_res and "desc" in gemma_res:
            tag = gemma_res.get("tag", item["tag"])
            title = gemma_res.get("title", item["title"])
            desc = gemma_res.get("desc", item["desc"])
        else:
            tag = item["tag"]
            title = item["title"]
            desc = item["desc"]

        careers.append({
            "id": item["id"],
            "name": item["name"],
            "keywords": item["keywords"],
            "tag": tag,
            "title": title,
            "desc": desc
        })

    # 生成前端可直接調用的 js 檔
    js_content = "/**\n * 字戀 (WordChain) - 百工百業職業神算行話庫 (由 Gemma 賦能擴展)\n */\n"
    js_content += "window.CAREER_DATABASE = " + json.dumps(careers, ensure_ascii=False, indent=2) + ";\n"

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(js_content)

    print(f"✅ 百工百業職業神算數據庫已成功構建至：{output_path}")
    return careers

